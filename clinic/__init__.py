"""
clinic —— 临床数据处理的 Python 工具包
=======================================

本包把教程中反复出现的通用逻辑抽取成可复用函数，供 `cases/` 下的案例脚本调用，
也供你直接在自己的项目里 `import`。

模块
----
- ``io``      : 读写 XPT / SAS7BDAT / CSV / Excel，保留变量标签
- ``derive``  : 派生逻辑（SAS 兼容的舍入、年龄分组、日期处理等）
- ``report``  : TFL 报表构造（n (%) 格式化、描述统计、导出）
- ``qc``      : 数据质量检查规则
- ``agent_tools`` : 暴露给 LLM Agent 的工具集

设计原则
--------
1. **与 SAS 结果对齐优先于"Pythonic"** —— 例如 ``sas_round`` 复刻 SAS 的四舍五入，
   而不是用 Python 内置的银行家舍入。
2. **边界规则显式化** —— 所有分组/区间判断都写明边界归属，便于 QC 核对。
3. **失败要响** —— 关键校验失败时抛异常（对应 SAS 的 %abort），而不是默默产出错误结果。
"""

